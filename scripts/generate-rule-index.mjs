import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../src/rules/", import.meta.url);
const imports = [];
const policies = [];
const artifactNames = [];
const ids = new Set();
const basename = /^[a-zA-Z0-9_-][a-zA-Z0-9._-]*$|^\.[a-zA-Z0-9_-][a-zA-Z0-9._-]*$/u;

for (const owner of (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()) {
  for (const file of (await readdir(new URL(owner + "/", root)))
    .filter((name) => name.endsWith(".json"))
    .sort()) {
    const path = owner + "/" + file;
    const rule = JSON.parse(await readFile(new URL(path, root), "utf8"));
    const id = owner + "." + file.slice(0, -5);
    if (!/^[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*$/u.test(id) || rule.id !== id || ids.has(id))
      throw new Error("Invalid or duplicate rule ID in " + path);
    ids.add(id);
    if (rule.kind === "project-artifacts") {
      if (
        Object.keys(rule).some((key) => !["id", "kind", "names"].includes(key)) ||
        !Array.isArray(rule.names) ||
        !rule.names.length
      )
        throw new Error("Invalid project-artifacts rule in " + path);
      for (const name of rule.names) {
        if (
          typeof name !== "string" ||
          !basename.test(name) ||
          name.toLowerCase() === ".git" ||
          artifactNames.includes(name)
        )
          throw new Error("Unsafe or duplicate project artifact in " + path);
        artifactNames.push(name);
      }
    } else if (rule.kind === "provider-file" && rule.provider === owner) {
      const binding = "rule" + policies.length;
      imports.push("import " + binding + ' from "./' + path + '" with { type: "json" };');
      policies.push(binding);
    } else {
      throw new Error("Unrecognized rule kind or owner in " + path);
    }
  }
}

const source = [
  "// Generated by pnpm rules:generate. Edit the owner rule files instead.",
  ...imports,
  "",
  "// oxfmt-ignore",
  "export const fileRuleDefinitions = [",
  ...policies.map((binding) => "  " + binding + ","),
  "];",
  "// oxfmt-ignore",
  "export const artifactNames = [",
  ...artifactNames.map((name) => "  " + JSON.stringify(name) + ","),
  "] as const;",
  "",
].join("\n");
const output = new URL("builtin.generated.ts", root);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== source)
    throw new Error("Stale " + fileURLToPath(output) + ". Run pnpm rules:generate.");
} else {
  await writeFile(output, source);
}
